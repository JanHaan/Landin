def outputs() -> dict[Path, str]:
    tm = textmate()
    result = {
        ROOT / "textmate/syntaxes/landin.tmLanguage.json": tm,
        ROOT / "sublime/Landin.tmLanguage": tm,
        ROOT / "vim/syntax/landin.vim": vim(),
        ROOT / "nano/landin.nanorc": nano(),
        ROOT / "kate/landin.xml": kate(),
        ROOT / "notepad-plus-plus/Landin.xml": notepad_plus_plus(),
    }
    query_copies = {
        "nvim/queries/landin/highlights.scm": "highlights.scm",
        "nvim/queries/landin/indents.scm": "indents.scm",
        "nvim/queries/landin/folds.scm": "folds.scm",
        "nvim/queries/landin/locals.scm": "locals.scm",
        "nvim/queries/landin/textobjects.scm": "textobjects.scm",
        "nvim/queries/landin/tags.scm": "tags.scm",
        "helix/runtime/queries/landin/highlights.scm": "highlights.scm",
        "helix/runtime/queries/landin/indents.scm": "indents.scm",
        "helix/runtime/queries/landin/folds.scm": "folds.scm",
        "helix/runtime/queries/landin/textobjects.scm": "textobjects.scm",
        "helix/runtime/queries/landin/locals.scm": "locals.scm",
        "helix/runtime/queries/landin/tags.scm": "tags.scm",
        "zed/languages/landin/highlights.scm": "highlights.scm",
        "zed/languages/landin/indents.scm": "indents.scm",
        "zed/languages/landin/brackets.scm": "brackets.scm",
    }
    for destination, source in query_copies.items():
        result[ROOT / destination] = (ROOT / "tree-sitter/queries" / source).read_text(
            encoding="utf-8"
        )
    return result


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale: list[Path] = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT.parent))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        for path in stale:
            print(f"stale generated highlighter: {path}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
