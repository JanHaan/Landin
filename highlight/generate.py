#!/usr/bin/env python3
"""Generate the regex-based Landin editor grammars from one vocabulary."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from xml.sax.saxutils import escape

from landin_highlight import BUILTIN_MODULES, CONSTANTS, KEYWORDS, TYPES


ROOT = Path(__file__).resolve().parent
GENERATED = "Generated by highlight/generate.py; do not edit by hand."


def words(values: set[str]) -> str:
    return "|".join(sorted(values, key=lambda value: (-len(value), value)))


def textmate() -> str:
    keyword = rf"\b(?:{words(KEYWORDS)})\b"
    builtin_type = rf"\b(?:{words(TYPES)}|[ui](?:0|[1-9][0-9]{{0,2}}))\b"
    constants = rf"\b(?:{words(CONSTANTS)})\b"
    modules = rf"\b(?:{words(BUILTIN_MODULES)})\b"
    grammar = {
        "name": "Landin",
        "scopeName": "source.landin",
        "fileTypes": ["ldn"],
        "patterns": [
            {"include": "#comments"},
            {"include": "#literals"},
            {"match": builtin_type, "name": "storage.type.builtin.landin"},
            {"match": constants, "name": "constant.language.landin"},
            {"match": modules, "name": "support.module.landin"},
            {"match": keyword, "name": "keyword.control.landin"},
            {
                "match": r"\b([a-z_][a-z0-9_]*)(?=\s*:\s*(?:type|atom)\b)",
                "name": "entity.name.type.landin",
            },
            {
                "match": r"\b([a-z_][a-z0-9_]*)(?=\s*:\s*\([^\n]*\)\s*->)",
                "name": "entity.name.function.landin",
            },
            {
                "match": r"\b[a-z_][a-z0-9_]*(?=\s*\()",
                "name": "entity.name.function.call.landin",
            },
            {
                "match": r"(?<=\.)[a-z_][a-z0-9_]*\b",
                "name": "variable.other.member.landin",
            },
            {
                "match": r"(?:\+%|-%|\*%|:=|->|\.\.<|\.\.|<<|>>|==|<>|<=|>=|[-+*/%<>=!&|^~])",
                "name": "keyword.operator.landin",
            },
        ],
        "repository": {
            "comments": {
                "patterns": [
                    {"match": r"---.*$", "name": "comment.line.documentation.landin"},
                    {"include": "#block-comment"},
                    {"match": r"--.*$", "name": "comment.line.double-dash.landin"},
                ]
            },
            "block-comment": {
                "begin": r"--\(",
                "beginCaptures": {"0": {"name": "punctuation.definition.comment.begin.landin"}},
                "end": r"\)--",
                "endCaptures": {"0": {"name": "punctuation.definition.comment.end.landin"}},
                "name": "comment.block.landin",
                "patterns": [{"include": "#block-comment"}],
            },
            "literals": {
                "patterns": [
                    {
                        "begin": r'("{3,})',
                        "end": r"\1",
                        "name": "string.quoted.other.raw.landin",
                    },
                    {
                        "begin": '"',
                        "end": '"|$',
                        "name": "string.quoted.double.landin",
                        "patterns": [{"match": r"\\.", "name": "constant.character.escape.landin"}],
                    },
                    {
                        "begin": "'",
                        "end": "'|$",
                        "name": "string.quoted.single.landin",
                        "patterns": [{"match": r"\\.", "name": "constant.character.escape.landin"}],
                    },
                    {
                        "match": r"\b(?:0[xX][0-9A-Fa-f_]+(?:\.[0-9A-Fa-f_]+)?(?:[pP][-+]?[0-9]+)?|0[bB][01_]+|0[oO][0-7_]+|[0-9][0-9_]*(?:\.(?!\.)[0-9_]+)?(?:[eE][-+]?[0-9]+)?)\b",
                        "name": "constant.numeric.landin",
                    },
                ]
            },
        },
        "metadata": {"comment": GENERATED},
    }
    return json.dumps(grammar, indent=2, ensure_ascii=False) + "\n"


def vim() -> str:
    def declarations(group: str, values: set[str]) -> str:
        return f"syntax keyword {group} {' '.join(sorted(values))}"

    return "\n".join(
        [
            f'" {GENERATED}',
            "if exists('b:current_syntax') | finish | endif",
            "syntax case match",
            "syntax keyword landinTodo TODO FIXME XXX contained",
            r'syntax region landinString start=/"/ skip=/\\./ end=/"/ oneline',
            r"syntax region landinCharacter start=/'/ skip=/\\./ end=/'/ oneline",
            r'syntax region landinRawString start=/\z("\{3,}\)/ end=/\z1/ keepend',
            r"syntax match landinNumber /\<\%(0[xX][0-9A-Fa-f_]\+\%([.][0-9A-Fa-f_]\+\)\?\%([pP][-+]\?[0-9]\+\)\?\|0[bB][01_]\+\|0[oO][0-7_]\+\|[0-9][0-9_]*\%([.][0-9_]\+\)\?\%([eE][-+]\?[0-9]\+\)\?\)\>/",
            declarations("landinKeyword", KEYWORDS),
            declarations("landinType", TYPES),
            declarations("landinConstant", CONSTANTS),
            declarations("landinBuiltinModule", BUILTIN_MODULES),
            r"syntax match landinWidthType /\<[ui]\%(0\|[1-9][0-9]\{0,2}\)\>/",
            r"syntax match landinFunction /\<[a-z_][a-z0-9_]*\ze\s*(/",
            r"syntax match landinMember /\.\zs[a-z_][a-z0-9_]*/",
            r"syntax match landinOperator /\%(+%\|-%\|\*%\|:=\|->\|\.\.<\|\.\.\|<<\|>>\|==\|<>\|<=\|>=\|[-+*\/%<>=!&|^~]\)/",
            "syntax match landinLineComment /--.*$/ contains=landinTodo",
            "syntax match landinDocComment /---.*$/ contains=landinTodo",
            r"syntax region landinBlockComment start=/--(/ end=/)--/ contains=landinBlockComment,landinTodo keepend extend",
            "highlight default link landinKeyword Keyword",
            "highlight default link landinType Type",
            "highlight default link landinWidthType Type",
            "highlight default link landinConstant Constant",
            "highlight default link landinBuiltinModule Include",
            "highlight default link landinFunction Function",
            "highlight default link landinMember Identifier",
            "highlight default link landinOperator Operator",
            "highlight default link landinNumber Number",
            "highlight default link landinString String",
            "highlight default link landinRawString String",
            "highlight default link landinCharacter Character",
            "highlight default link landinLineComment Comment",
            "highlight default link landinDocComment SpecialComment",
            "highlight default link landinBlockComment Comment",
            "highlight default link landinTodo Todo",
            "let b:current_syntax = 'landin'",
            "",
        ]
    )


def nano() -> str:
    color = lambda name, values: f'color {name} "\\<({"|".join(sorted(values))})\\>"'
    return "\n".join(
        [
            f"# {GENERATED}",
            'syntax "landin" "\\.ldn$"',
            color("brightblue", KEYWORDS),
            color("brightgreen", TYPES),
            color("magenta", CONSTANTS),
            color("cyan", BUILTIN_MODULES),
            'color brightgreen "\\<[ui](0|[1-9][0-9]{0,2})\\>"',
            'color brightcyan "\\<[a-z_][a-z0-9_]*[[:space:]]*\\("',
            'color yellow "\\<((0[xX][0-9A-Fa-f_]+)|(0[bB][01_]+)|(0[oO][0-7_]+)|([0-9][0-9_]*))\\>"',
            'color brightmagenta start="\\\"" end="\\\""',
            'color brightblack "---.*$"',
            'color brightblack "--.*$"',
            'color brightblack start="--\\(" end="\\)--"',
            "",
        ]
    )


def kate() -> str:
    items = lambda values: "".join(f"<item>{escape(value)}</item>" for value in sorted(values))
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- {GENERATED} -->
<!DOCTYPE language SYSTEM "language.dtd">
<language name="Landin" section="Sources" extensions="*.ldn" mimetype="text/x-landin" version="1" kateversion="5.0" author="Landin contributors" license="MIT OR Apache-2.0">
  <highlighting>
    <list name="keywords">{items(KEYWORDS)}</list>
    <list name="types">{items(TYPES)}</list>
    <list name="constants">{items(CONSTANTS)}</list>
    <list name="modules">{items(BUILTIN_MODULES)}</list>
    <contexts>
      <context name="Normal" attribute="Normal Text" lineEndContext="#stay">
        <StringDetect String="--(" attribute="Comment" context="Block Comment"/>
        <Detect2Chars char="-" char1="-" attribute="Comment" context="Line Comment"/>
        <keyword String="keywords" attribute="Keyword"/>
        <keyword String="types" attribute="Data Type"/>
        <keyword String="constants" attribute="Constant"/>
        <keyword String="modules" attribute="Import"/>
        <RegExpr String="\\b[ui](0|[1-9][0-9]{{0,2}})\\b" attribute="Data Type"/>
        <RegExpr String="\\b(0[xX][0-9A-Fa-f_]+|0[bB][01_]+|0[oO][0-7_]+|[0-9][0-9_]*)\\b" attribute="Number"/>
        <DetectChar char="&quot;" attribute="String" context="String"/>
        <DetectChar char="'" attribute="Char" context="Char"/>
      </context>
      <context name="Line Comment" attribute="Comment" lineEndContext="#pop"/>
      <context name="Block Comment" attribute="Comment" lineEndContext="#stay">
        <StringDetect String="--(" context="Block Comment"/>
        <StringDetect String=")--" context="#pop"/>
      </context>
      <context name="String" attribute="String" lineEndContext="#pop">
        <HlCStringChar attribute="Special Character"/>
        <DetectChar char="&quot;" context="#pop"/>
      </context>
      <context name="Char" attribute="Char" lineEndContext="#pop">
        <HlCChar attribute="Special Character"/>
        <DetectChar char="'" context="#pop"/>
      </context>
    </contexts>
    <itemDatas>
      <itemData name="Normal Text" defStyleNum="dsNormal"/>
      <itemData name="Keyword" defStyleNum="dsKeyword"/>
      <itemData name="Data Type" defStyleNum="dsDataType"/>
      <itemData name="Constant" defStyleNum="dsConstant"/>
      <itemData name="Import" defStyleNum="dsImport"/>
      <itemData name="Number" defStyleNum="dsDecVal"/>
      <itemData name="String" defStyleNum="dsString"/>
      <itemData name="Char" defStyleNum="dsChar"/>
      <itemData name="Special Character" defStyleNum="dsSpecialChar"/>
      <itemData name="Comment" defStyleNum="dsComment"/>
    </itemDatas>
  </highlighting>
  <general><comments><comment name="singleLine" start="--"/><comment name="multiLine" start="--(" end=")--" region="Block Comment"/></comments><keywords casesensitive="1"/></general>
</language>
'''


